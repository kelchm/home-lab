import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const prototype = new URL('../../fixtures/reference/', import.meta.url);
const read = (file) => readFileSync(new URL(file, prototype), 'utf8');
const sources = ['adapters.js', 'home-model.js'];
const names = ['seriesOf', 'instant', 'scalar', 'withGaps', 'smallestStep', 'hostRows', 'hostsUrl', 'HOST_STATES', 'dailyReview', 'dailyEpisodes', 'dailyIdentity', 'dailyBands'];
const hashes = sources.map((file) => `${file} sha256:${createHash('sha256').update(read(file)).digest('hex').slice(0, 16)}`);
const target = new URL('../src/model/semantics.js', import.meta.url);
writeFileSync(target, `// GENERATED by tools/vendor-model.mjs. Do not edit; change the reviewed sources.\n// ${hashes.join('\n// ')}\n${sources.map(read).join('\n')}\nexport { ${names.join(', ')} };\n`);
console.log(hashes.join('\n'));
